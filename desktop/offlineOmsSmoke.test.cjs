'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const initSqlJs=require('sql.js')
const {handleOfflineOms}=require('./offlineOms.cjs')
const {mutateLocalRecord,listCombinedRecords}=require('./standaloneRecords.cjs')
async function main(){
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-oms-481-'))
 try{
  const SQL=await initSqlJs({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE snapshot_manifest (table_name TEXT,row_count INTEGER)')
  db.run('CREATE TABLE snapshot_rows (table_name TEXT,row_index INTEGER,row_json TEXT)')
  const file=path.join(directory,'nizamia-app2a.sqlite')
  fs.writeFileSync(file,Buffer.from(db.export()))
  db.close()
  const invoke=(action,method='GET',payload={})=>{
   const url=new URL('https://local.invalid/api/oms?action='+encodeURIComponent(action))
   return handleOfflineOms(directory,url,new Request(url,{method,...(method==='POST'?{headers:{'content-type':'application/json'},body:JSON.stringify({action,...payload})}:{})}))
  }
  let response=await invoke('testing')
  assert.equal(response.status,200)
  let result=await response.json()
  assert.deepEqual(result.orders,[])
  assert.deepEqual(result.requirements,[])
  response=await invoke('unsupported')
  assert.equal(response.status,501)
  assert.match((await response.json()).error,/not yet available offline/)
  const buyer=await mutateLocalRecord(directory,{action:'create',table:'buyers',fields:{name:'Test Buyer'}})
  const order=await mutateLocalRecord(directory,{action:'create',table:'orders',fields:{job_number:'OFFLINE-481'}})
  response=await invoke('testing')
  result=await response.json()
  assert.equal(result.orders.find(row=>row.id===order.id).job_number,'OFFLINE-481')
  response=await invoke('createParcel','POST',{parcel:{items:[],custom_items:[],buyer_id:buyer.id}})
  assert.equal(response.status,200)
  const created=await response.json()
  assert.equal(created.offline,true)
  assert.match(created.id,/^PAR-\\d{2}-\\d{3}$/)
  const parcels=await listCombinedRecords(directory,'parcels')
  assert.equal(parcels.length,1)
  assert.equal(parcels[0].status,'Draft')
  response=await invoke('createParcel','POST',{parcel:{items:'invalid',custom_items:[]}})
  assert.equal(response.status,400)
  assert.equal((await listCombinedRecords(directory,'parcels')).length,1,'Invalid input must not mutate records')
  response=await invoke('save','POST',{type:'snapshots',parcelId:created.id,addressId:'missing'})
  assert.equal(response.status,400)
  assert.equal((await listCombinedRecords(directory,'parcel_invoice_snapshots')).length,0)
  console.log('Offline OMS smoke tests passed: reads, parcel creation, invalid-input safety and unsupported action')
 }finally{fs.rmSync(directory,{recursive:true,force:true})}
}
main().catch(error=>{console.error(error);process.exitCode=1})
