'use strict'
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const initSqlJs=require('sql.js')
const {mutateLocalRecord,listLocalRecords,listCombinedRecords,createLocalRecordBatch}=require('./standaloneRecords.cjs')
async function main(){
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-local-crud-'))
 try{
  const SQL=await initSqlJs({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE snapshot_manifest (table_name TEXT,row_count INTEGER)')
  db.run("INSERT INTO snapshot_manifest VALUES ('orders',1)")
  db.run('CREATE TABLE snapshot_rows (table_name TEXT,row_index INTEGER,row_json TEXT)')
  db.run('INSERT INTO snapshot_rows VALUES (?,?,?)',['orders',0,JSON.stringify({id:'cloud1',job_number:'J100'})])
  const file=path.join(dir,'nizamia-app2a.sqlite')
  fs.writeFileSync(file,Buffer.from(db.export()));db.close()
  const batch=await createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Buyer One'},{name:'Buyer Two'}]})
  assert.equal(batch.length,2)
  assert.equal((await listLocalRecords(dir,'buyers')).length,2)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Valid'},{name:''}]}),/required/)
  assert.equal((await listLocalRecords(dir,'buyers')).length,2)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'buyers',rows:[]}),/Batch requires/)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'users',rows:[{name:'No'}]}),/Unsupported/)
  const a=await mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'LOCAL1',buyer_name:'Buyer',total_qty:100}})
  assert.match(a.id,/^local-/)
  assert.equal((await listLocalRecords(dir,'orders')).length,1)
  assert.equal((await listCombinedRecords(dir,'orders')).length,2)
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1')._local_only,false)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:a.id,fields:{job_number:'LOCAL2',buyer_name:'Buyer',total_qty:200}})
  assert.equal((await listLocalRecords(dir,'orders'))[0].total_qty,200)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J101'}})
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1').job_number,'J101')
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1')._local_edited,true)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J102'}})
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1').job_number,'J102')
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'nonexistent',fields:{job_number:'x'}}),/not found/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{password:'unsafe'}}),/Unsupported/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{total_qty:-1/0}}),/Invalid number|Unsupported/)
  await mutateLocalRecord(dir,{action:'delete',table:'orders',id:'cloud1'})
  assert.equal((await listCombinedRecords(dir,'orders')).some(x=>x.id==='cloud1'),false)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J103'}}),/already deleted/)
  assert.equal((await listLocalRecords(dir,'orders')).length,1)
  assert.equal((await listCombinedRecords(dir,'orders')).length,1)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'TEST',buyer_name:'Buyer',password:'secret'}}),/Unsupported/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'create',table:'users',fields:{name:'X'}}),/Unsupported/)
  const cost=await mutateLocalRecord(dir,{action:'create',table:'costing',fields:{cost_sheet_number:'C1',order_id:a.id,fabric_cost:3.45}})
  const meeting=await mutateLocalRecord(dir,{action:'create',table:'pp_meetings',fields:{meeting_reference:'PP1',order_id:a.id,meeting_date:'2026-11-14'}})
  assert.equal((await listLocalRecords(dir,'costing'))[0].fabric_cost,3.45)
  assert.equal((await listLocalRecords(dir,'pp_meetings'))[0].meeting_reference,'PP1')
  const plan=await mutateLocalRecord(dir,{action:'create',table:'production_plans',fields:{plan_reference:'PL1',order_id:a.id,department:'Cutting',planned_quantity:100}})
  assert.equal((await listLocalRecords(dir,'production_plans'))[0].planned_quantity,100)
  const persisted=new SQL.Database(fs.readFileSync(file))
  assert.equal(JSON.parse(persisted.exec('SELECT row_json FROM snapshot_rows')[0].values[0][0]).job_number,'J100')
  persisted.close()
  const linked=await mutateLocalRecord(dir,{action:'create',table:'production_daily_entries',fields:{order_id:a.id,department:'Cutting',quantity:10}})
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'delete',table:'orders',id:a.id}),/Cannot delete order/)
  await mutateLocalRecord(dir,{action:'delete',table:'production_daily_entries',id:linked.id})
  await mutateLocalRecord(dir,{action:'delete',table:'production_plans',id:plan.id})
  await mutateLocalRecord(dir,{action:'delete',table:'costing',id:cost.id})
  await mutateLocalRecord(dir,{action:'delete',table:'pp_meetings',id:meeting.id})
  await mutateLocalRecord(dir,{action:'delete',table:'orders',id:a.id})
  assert.equal((await listLocalRecords(dir,'orders')).length,0)
  process.stdout.write('Standalone offline CRUD integration passed.\\n')
 }finally{fs.rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
