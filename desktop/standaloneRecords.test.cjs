'use strict'
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const initSqlJs=require('sql.js')
const {mutateLocalRecord,listLocalRecords,listCombinedRecords,createLocalRecordBatch,mutateLocalRecordBatch,upsertLocalRecordBatch}=require('./standaloneRecords.cjs')
async function main(){
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-local-crud-'))
 try{
  const SQL=await initSqlJs({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE snapshot_manifest (table_name TEXT,row_count INTEGER)')
  db.run("INSERT INTO snapshot_manifest VALUES ('orders',1)")
  db.run('CREATE TABLE snapshot_rows (table_name TEXT,row_index INTEGER,row_json TEXT)')
  db.run('INSERT INTO snapshot_rows VALUES (?,?,?)',['orders',0,JSON.stringify({id:'cloud1',job_number:'J100'})])
  const file=path.join(dir,'nizamia-app2a.sqlite')
  fs.writeFileSync(file,Buffer.from(db.export()));db.close()
  const batch=await createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Buyer One'},{name:'Buyer Two'}]})
  assert.equal(batch.length,2)
  assert.equal((await listLocalRecords(dir,'buyers')).length,2)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Valid'},{name:''}]}),/required/)
  assert.equal((await listLocalRecords(dir,'buyers')).length,2)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'buyers',rows:[]}),/Batch requires/)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'users',rows:[{name:'No'}]}),/Unsupported/)
  for(const table of ["size_groups","size_group_colors","size_group_breakdown","order_processes","work_order_items","payment_settlements","production_batches","production_batch_orders","sample_comments"]){
    const row=await mutateLocalRecord(dir,{action:'create',table,fields:{name:'Offline '+table}})
    assert.equal((await listLocalRecords(dir,table)).find(x=>x.id===row.id).name,'Offline '+table)
    await mutateLocalRecord(dir,{action:'update',table,id:row.id,fields:{name:'Updated '+table}})
    assert.equal((await listCombinedRecords(dir,table)).find(x=>x.id===row.id).name,'Updated '+table)
    await mutateLocalRecord(dir,{action:'delete',table,id:row.id})
    assert.equal((await listLocalRecords(dir,table)).length,0)
  }
  const multi=await createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Batch A'},{name:'Batch B'}]})
  await mutateLocalRecordBatch(dir,{action:'update',table:'buyers',ids:multi.map(r=>r.id),fields:{country:'Pakistan'}})
  assert.equal((await listLocalRecords(dir,'buyers')).filter(r=>r.country==='Pakistan').length,2)
  await assert.rejects(()=>mutateLocalRecordBatch(dir,{action:'delete',table:'buyers',ids:[multi[0].id,'local-missing']}),/not found/)
  assert.equal((await listLocalRecords(dir,'buyers')).filter(r=>multi.some(x=>x.id===r.id)).length,2)
  await mutateLocalRecordBatch(dir,{action:'delete',table:'buyers',ids:multi.map(r=>r.id)})
  assert.equal((await listLocalRecords(dir,'buyers')).filter(r=>multi.some(x=>x.id===r.id)).length,0)
  await mutateLocalRecordBatch(dir,{action:'update',table:'orders',ids:['cloud1'],fields:{job_number:'BATCH-UPDATED'}})
  assert.equal((await listCombinedRecords(dir,'orders')).find(r=>r.id==='cloud1').job_number,'BATCH-UPDATED')
  for(const table of ["finishing_packs","fitting_blocks","library_items","sample_logs","fitting","work_order_changelog","shipping_bookings","shipping_booking_lines","shipping_booking_shipments"]){
    const row=await mutateLocalRecord(dir,{action:'create',table,fields:{name:'Offline '+table}})
    assert.equal((await listCombinedRecords(dir,table)).find(x=>x.id===row.id).name,'Offline '+table)
    await mutateLocalRecord(dir,{action:'update',table,id:row.id,fields:{name:'Edited '+table}})
    assert.equal((await listLocalRecords(dir,table)).find(x=>x.id===row.id).name,'Edited '+table)
    await mutateLocalRecord(dir,{action:'delete',table,id:row.id})
    assert.equal((await listLocalRecords(dir,table)).length,0)
  }
  // End-to-end purchasing, production and shipping relationships.
  const buyer=await mutateLocalRecord(dir,{action:'create',table:'buyers',fields:{name:'Workflow Buyer'}})
  const parentOrder=await mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'WF-1',buyer_name:'Workflow Buyer',total_qty:200}})
  const po=await mutateLocalRecord(dir,{action:'create',table:'purchase_orders',fields:{order_id:parentOrder.id,po_number:'PO-WF-1',supplier_name:'Workflow Supplier'}})
  const poLines=await createLocalRecordBatch(dir,{table:'purchase_order_items',rows:[{po_id:po.id,description:'Fabric',qty:100},{po_id:po.id,description:'Trims',qty:200}]})
  assert.equal((await listCombinedRecords(dir,'purchase_order_items')).filter(r=>r.po_id===po.id).length,2)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'delete',table:'purchase_orders',id:po.id}),/linked/)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'purchase_order_items',rows:[{po_id:po.id,description:'Valid'},{po_id:'local-missing',description:'Invalid'}]}),/does not exist/)
  assert.equal((await listLocalRecords(dir,'purchase_order_items')).length,2)
  await mutateLocalRecordBatch(dir,{action:'delete',table:'purchase_order_items',ids:poLines.map(r=>r.id)})
  await mutateLocalRecord(dir,{action:'delete',table:'purchase_orders',id:po.id})
  const group=await mutateLocalRecord(dir,{action:'create',table:'size_groups',fields:{order_id:parentOrder.id,group_name:'3-8 Years'}})
  const color=await mutateLocalRecord(dir,{action:'create',table:'size_group_colors',fields:{size_group_id:group.id,color_name:'Indigo'}})
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'delete',table:'size_groups',id:group.id}),/linked/)
  await mutateLocalRecord(dir,{action:'delete',table:'size_group_colors',id:color.id})
  await mutateLocalRecord(dir,{action:'delete',table:'size_groups',id:group.id})
  const shipment=await mutateLocalRecord(dir,{action:'create',table:'shipments',fields:{order_id:parentOrder.id,shipment_number:'SHIP-1'}})
  const shipmentLine=await mutateLocalRecord(dir,{action:'create',table:'shipment_lines',fields:{shipment_id:shipment.id,shipped_qty:50}})
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'delete',table:'shipments',id:shipment.id}),/linked/)
  await mutateLocalRecord(dir,{action:'delete',table:'shipment_lines',id:shipmentLine.id})
  await mutateLocalRecord(dir,{action:'delete',table:'shipments',id:shipment.id})
  await mutateLocalRecord(dir,{action:'delete',table:'orders',id:parentOrder.id})
  await mutateLocalRecord(dir,{action:'delete',table:'buyers',id:buyer.id})
  const firstSettlement=await upsertLocalRecordBatch(dir,{table:'payment_settlements',onConflict:'shipment_id',rows:[{shipment_id:'S1',payload:{received:100}},{shipment_id:'S2',payload:{received:200}}]})
  assert.equal(firstSettlement.length,2)
  const secondSettlement=await upsertLocalRecordBatch(dir,{table:'payment_settlements',onConflict:'shipment_id',rows:[{shipment_id:'S1',payload:{received:300}},{shipment_id:'S3',payload:{received:400}}]})
  assert.equal(secondSettlement[0].id,firstSettlement[0].id)
  assert.equal((await listLocalRecords(dir,'payment_settlements')).length,3)
  assert.equal((await listLocalRecords(dir,'payment_settlements')).find(r=>r.shipment_id==='S1').payload.received,300)
  await assert.rejects(()=>upsertLocalRecordBatch(dir,{table:'payment_settlements',onConflict:'shipment_id',rows:[{shipment_id:'S1',payload:{received:999}},{shipment_id:'S4',password:'bad'}]}),/Unsupported/)
  assert.equal((await listLocalRecords(dir,'payment_settlements')).find(r=>r.shipment_id==='S1').payload.received,300)
  const a=await mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'LOCAL1',buyer_name:'Buyer',total_qty:100}})
  assert.match(a.id,/^local-/)
  assert.equal((await listLocalRecords(dir,'orders')).length,1)
  assert.equal((await listCombinedRecords(dir,'orders')).length,2)
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1')._local_only,false)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:a.id,fields:{job_number:'LOCAL2',buyer_name:'Buyer',total_qty:200}})
  assert.equal((await listLocalRecords(dir,'orders'))[0].total_qty,200)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J101'}})
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1').job_number,'J101')
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1')._local_edited,true)
  await mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J102'}})
  assert.equal((await listCombinedRecords(dir,'orders')).find(x=>x.id==='cloud1').job_number,'J102')
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'nonexistent',fields:{job_number:'x'}}),/not found/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{password:'unsafe'}}),/Unsupported/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{_local_edited:true}}),/Unsupported/)
  await assert.rejects(()=>createLocalRecordBatch(dir,{table:'buyers',rows:[{name:'Safe'},{name:'Bad',_local_edited:true}]}),/Unsupported/)
  assert.equal((await listLocalRecords(dir,'buyers')).length,2)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{total_qty:-1/0}}),/Invalid number|Unsupported/)
  await mutateLocalRecord(dir,{action:'delete',table:'orders',id:'cloud1'})
  assert.equal((await listCombinedRecords(dir,'orders')).some(x=>x.id==='cloud1'),false)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'update',table:'orders',id:'cloud1',fields:{job_number:'J103'}}),/already deleted/)
  assert.equal((await listLocalRecords(dir,'orders')).length,1)
  assert.equal((await listCombinedRecords(dir,'orders')).length,1)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'TEST',buyer_name:'Buyer',password:'secret'}}),/Unsupported/)
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'create',table:'users',fields:{name:'X'}}),/Unsupported/)
  const cost=await mutateLocalRecord(dir,{action:'create',table:'costing',fields:{cost_sheet_number:'C1',order_id:a.id,fabric_cost:3.45}})
  const meeting=await mutateLocalRecord(dir,{action:'create',table:'pp_meetings',fields:{meeting_reference:'PP1',order_id:a.id,meeting_date:'2026-11-14'}})
  assert.equal((await listLocalRecords(dir,'costing'))[0].fabric_cost,3.45)
  assert.equal((await listLocalRecords(dir,'pp_meetings'))[0].meeting_reference,'PP1')
  const plan=await mutateLocalRecord(dir,{action:'create',table:'production_plans',fields:{plan_reference:'PL1',order_id:a.id,department:'Cutting',planned_quantity:100}})
  assert.equal((await listLocalRecords(dir,'production_plans'))[0].planned_quantity,100)
  const persisted=new SQL.Database(fs.readFileSync(file))
  assert.equal(JSON.parse(persisted.exec('SELECT row_json FROM snapshot_rows')[0].values[0][0]).job_number,'J100')
  persisted.close()
  const linked=await mutateLocalRecord(dir,{action:'create',table:'production_daily_entries',fields:{order_id:a.id,department:'Cutting',quantity:10}})
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'delete',table:'orders',id:a.id}),/Cannot delete order/)
  await mutateLocalRecord(dir,{action:'delete',table:'production_daily_entries',id:linked.id})
  await mutateLocalRecord(dir,{action:'delete',table:'production_plans',id:plan.id})
  await mutateLocalRecord(dir,{action:'delete',table:'costing',id:cost.id})
  await mutateLocalRecord(dir,{action:'delete',table:'pp_meetings',id:meeting.id})
  await mutateLocalRecord(dir,{action:'delete',table:'orders',id:a.id})
  assert.equal((await listLocalRecords(dir,'orders')).length,0)
  process.stdout.write('Standalone offline CRUD integration passed.\\n')
 }finally{fs.rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
