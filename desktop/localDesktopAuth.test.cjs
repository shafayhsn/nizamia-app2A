'use strict'
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const {createLocalAuth}=require('./localDesktopAuth.cjs')
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-auth-test-'))
try{
 const auth=createLocalAuth(dir)
 assert.equal(auth.status().setupRequired,true)
 assert.equal(auth.isAuthenticated(),false)
 assert.throws(()=>auth.setup('operator','short'),/12 characters/)
 const created=auth.setup('operator','very-secure-local-passphrase')
 assert.equal(created.user.username,'operator')
 assert.equal(auth.status().setupRequired,false)
 assert.equal(auth.isAuthenticated(),true)
 assert.throws(()=>auth.setup('another','another-long-passphrase'),/already exists/)
 auth.logout()
 assert.equal(auth.isAuthenticated(),false)
 assert.throws(()=>auth.login('operator','wrong'),/Invalid credentials/)
 assert.equal(auth.login('operator','very-secure-local-passphrase').authenticated,true)
 assert.equal(auth.status().user.username,'operator')
 const raw=fs.readFileSync(path.join(dir,'desktop-local-account.json'),'utf8')
 assert.equal(raw.includes('very-secure-local-passphrase'),false)
 assert.equal(fs.statSync(path.join(dir,'desktop-local-account.json')).mode&0o777,0o600)
 console.log('Local desktop authentication tests passed')
}finally{fs.rmSync(dir,{recursive:true,force:true})}
