'use strict'
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const initSqlJs=require('sql.js')
const {FORMS,normalizeForm}=require('./standaloneForms.cjs')
const {mutateLocalRecord}=require('./standaloneRecords.cjs')
const {systemReport}=require('./offlineSystemReports.cjs')
async function main(){
 assert.equal(Object.keys(FORMS).length,9)
 assert.equal(normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',total_qty:'120'}).total_qty,120)
 assert.throws(()=>normalizeForm('orders',{job_number:'',buyer_name:'Buyer'}),/required/)
 assert.equal(normalizeForm('purchase_orders',{po_number:'P-1',supplier_name:'Mill',unit_price:'2.75'}).unit_price,2.75)
 assert.equal(normalizeForm('shipments',{shipment_number:'S-1',quantity:'250'}).quantity,250)
 assert.equal(normalizeForm('production_daily_entries',{order_id:'local-1',department:'Cutting',line:'Line A'}).line,'Line A')
 assert.equal(normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'2026-11-14'}).ex_factory_date,'2026-11-14')
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'not-a-date'}),/Invalid/)
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'2026-02-30'}),/Invalid/)
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'2026-13-01'}),/Invalid/)
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'2025-02-29'}),/Invalid/)
 assert.equal(normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',ex_factory_date:'2028-02-29'}).ex_factory_date,'2028-02-29')
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',total_qty:'bad'}),/non-negative/)
 assert.throws(()=>normalizeForm('orders',{job_number:'J01',buyer_name:'Buyer',total_qty:'1.5'}),/whole number/)
 assert.throws(()=>normalizeForm('shipments',{shipment_number:'S-1',quantity:'2.25'}),/whole number/)
 assert.throws(()=>normalizeForm('production_daily_entries',{order_id:'local-1',department:'Cutting',quantity:'9007199254740992'}),/whole number/)
 assert.equal(normalizeForm('production_daily_entries',{order_id:'local-1',department:'Cutting',quantity:'0'}).quantity,0)
 assert.equal(normalizeForm('purchase_orders',{po_number:'P-1',supplier_name:'Mill',unit_price:'2.75'}).unit_price,2.75)
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-form-report-'))
 try{
  const SQL=await initSqlJs({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE snapshot_manifest (table_name TEXT,row_count INTEGER)')
  db.run('CREATE TABLE snapshot_rows (table_name TEXT,row_index INTEGER,row_json TEXT)')
  fs.writeFileSync(path.join(dir,'nizamia-app2a.sqlite'),Buffer.from(db.export()));db.close()
  const linked=await mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'LOCAL1',buyer_name:'Buyer A',total_qty:'100',status:'open'}})
  await assert.rejects(()=>mutateLocalRecord(dir,{action:'create',table:'production_daily_entries',fields:{order_id:'local-00000000-0000-0000-0000-000000000000',department:'Cutting',quantity:10}}),/does not exist/)
  await mutateLocalRecord(dir,{action:'create',table:'production_daily_entries',fields:{order_id:linked.id,department:'Cutting',production_date:'2026-11-14',quantity:40}})
  await mutateLocalRecord(dir,{action:'create',table:'orders',fields:{job_number:'LOCAL2',buyer_name:'Buyer A',total_qty:50,status:'open'}})
  const current=new SQL.Database(fs.readFileSync(path.join(dir,'nizamia-app2a.sqlite')))
  const report=systemReport(current,'orders_by_buyer')
  assert.equal(report.totalRecords,2);assert.equal(report.localRecords,2)
  assert.equal(report.rows[0].quantity,150)
  current.close()
  process.stdout.write('Standalone business forms and live local operational reports passed.\\n')
 }finally{fs.rmSync(dir,{recursive:true,force:true})}
}
main().catch(e=>{console.error(e);process.exitCode=1})
