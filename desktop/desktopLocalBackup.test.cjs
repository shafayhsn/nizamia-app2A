'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const crypto=require('node:crypto')
const initSqlJs=require('sql.js')
const {backupDatabaseToFile,restoreDatabaseFromFile}=require('./desktopLocalBackup.cjs')
async function main(){
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-backup-test-'))
 try{
  const live=path.join(root,'live'),backups=path.join(root,'backups')
  fs.mkdirSync(live);fs.mkdirSync(backups)
  const SQL=await initSqlJs({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE app_metadata (key TEXT PRIMARY KEY,value TEXT)')
  db.run("INSERT INTO app_metadata VALUES ('schema_version','1')")
  db.run('CREATE TABLE snapshot_manifest (table_name TEXT,row_count INTEGER)')
  db.run('CREATE TABLE snapshot_rows (table_name TEXT,row_index INTEGER,row_json TEXT)')
  db.run('CREATE TABLE offline_records (id TEXT PRIMARY KEY, value TEXT)')
  db.run('INSERT INTO offline_records VALUES (?,?)',['draft-1','keep this local data'])
  const source=path.join(live,'nizamia-app2a.sqlite')
  fs.writeFileSync(source,Buffer.from(db.export()));db.close()
  const before=fs.readFileSync(source),destination=path.join(backups,'verified.sqlite')
  const result=await backupDatabaseToFile({directory:live,destination})
  assert.equal(result.file,destination)
  assert.equal(result.size,before.length)
  assert.equal(result.sha256,crypto.createHash('sha256').update(before).digest('hex'))
  assert.deepEqual(fs.readFileSync(destination),before)
  const restored=new SQL.Database(fs.readFileSync(destination))
  assert.equal(restored.exec('PRAGMA integrity_check')[0].values[0][0],'ok')
  assert.equal(restored.exec('SELECT value FROM offline_records')[0].values[0][0],'keep this local data')
  restored.close()
  await assert.rejects(()=>backupDatabaseToFile({directory:live,destination}),/already exists/)
  await assert.rejects(()=>backupDatabaseToFile({directory:live,destination:path.join(live,'unsafe.sqlite')}),/outside/)
  assert.deepEqual(fs.readFileSync(source),before,'Backup must never modify live database')
  for(const state of ['pending','conflict']){
   const queued=new SQL.Database(Buffer.from(before))
   queued.run('CREATE TABLE offline_mutation_outbox(state TEXT, intent_json TEXT)')
   queued.run('INSERT INTO offline_mutation_outbox VALUES (?,?)',[state,'saved edit'])
   const active=Buffer.from(queued.export())
   queued.close()
   fs.writeFileSync(source,active)
   await assert.rejects(restoreDatabaseFromFile({directory:live,source:destination}),/contains local work/)
   assert.deepEqual(fs.readFileSync(source),active)
  }
  const withPending=new SQL.Database(Buffer.from(before))
  withPending.run('CREATE TABLE offline_draft_journal (state TEXT)')
  withPending.run("INSERT INTO offline_draft_journal VALUES ('pending')")
  const pending=Buffer.from(withPending.export())
  withPending.close()
  fs.writeFileSync(source,pending)
  await assert.rejects(restoreDatabaseFromFile({directory:live,source:destination}),/contains local work/)
  assert.deepEqual(fs.readFileSync(source),pending)
  const recovery=path.join(root,'recovery')
  fs.mkdirSync(recovery)
  const copy=await restoreDatabaseFromFile({directory:recovery,source:destination,separate:true})
  assert.deepEqual(fs.readFileSync(copy.file),before)
  await assert.rejects(restoreDatabaseFromFile({directory:recovery,source:destination,separate:true}),/EEXIST/)
  assert.deepEqual(fs.readFileSync(copy.file),before)
  const restore=await restoreDatabaseFromFile({directory:recovery,source:destination})
  assert.deepEqual(fs.readFileSync(path.join(recovery,restore.safetyBackup)),before)
  assert.deepEqual(fs.readFileSync(source),pending)
  const invalidDir=path.join(root,'invalid');fs.mkdirSync(invalidDir)
  fs.writeFileSync(path.join(invalidDir,'nizamia-app2a.sqlite'),Buffer.alloc(256,65))
  await assert.rejects(()=>backupDatabaseToFile({directory:invalidDir,destination:path.join(backups,'invalid.sqlite')}),/invalid SQLite header/)
  assert.equal(fs.existsSync(path.join(backups,'invalid.sqlite')),false)
  console.log('Mac local database backup tests passed: checksum, restore, overwrite and unsafe path protections')
 }finally{fs.rmSync(root,{recursive:true,force:true})}
}
main().catch(error=>{console.error(error);process.exitCode=1})
