'use strict'
// CP-18 static release guardrails: keep the remote app isolated from local SQLite.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8')
const main = read('main.cjs')
const viewer = read('snapshotViewer.cjs')
const preload = read('snapshotViewerPreload.cjs')
const importer = read('snapshotImport.cjs')
assert.match(main, /showLocalSnapshot\(null,getDatabaseDirectory\)/, 'Standalone offline app must be the startup default')
assert.doesNotMatch(main, /Standalone startup failed[\s\S]{0,200}createWindow\(\)/, 'Offline startup failure must not silently open the cloud app')
assert.doesNotMatch(main, /preload:\s*path\.join/, 'Remote window must not receive the local SQLite bridge')
assert.match(viewer, /event\.sender\.id !== viewer\.webContents\.id/, 'IPC must verify the caller window')
assert.match(viewer, /senderURL\.protocol !== 'file:'/, 'IPC must verify the local file origin')
assert.match(viewer, /'filteredRows'/, 'Read-only search action missing')
assert.match(viewer, /'relatedRows'/, 'Read-only relationship action missing')
assert.doesNotMatch(viewer, /\b(INSERT|UPDATE|DELETE|REPLACE)\s+(INTO|FROM|[a-z_])/i, 'Viewer must never write business records')
assert.match(importer, /EXCLUDED_TABLES = new Set\(\['users', 'permissions', 'roles'/, 'Do not import auth tables')
assert.doesNotMatch(preload, /\bwrite\s*:/, 'Do not expose a write method')
process.stdout.write('CP-18 release guardrails passed: remote isolation, read-only IPC and excluded auth tables.\\n')
