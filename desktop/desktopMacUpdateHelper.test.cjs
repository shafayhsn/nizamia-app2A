'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const {spawnSync}=require('node:child_process')
const file=path.join(__dirname,'desktopMacUpdateHelper.sh')
const content=fs.readFileSync(file,'utf8')
assert.match(content,/shasum -a 256/)
assert.match(content,/CFBundleIdentifier/)
assert.match(content,/CFBundleShortVersionString/)
assert.match(content,/ROLLBACK/) 
assert.ok(content.includes('rollback-$VERSION-$.app'))
assert.match(content,/START_VERIFIED/)
assert.match(content,/READY_TOKEN/)
assert.match(content,/kill -0/)
assert.match(content,/trap 'restore; cleanup' EXIT/)
const syntax=spawnSync('/bin/bash',['-n',file],{encoding:'utf8'})
assert.equal(syntax.status,0,syntax.stderr)
const noArgs=spawnSync('/bin/bash',[file],{encoding:'utf8'})
assert.equal(noArgs.status,64)
console.log('External Mac installer helper syntax and fail-closed checks passed')
