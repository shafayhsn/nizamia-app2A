'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const os=require('node:os')
const {prepareWorkspace,archivePdf}=require('./nzosWorkspace.cjs')
test('migrates verified SQLite bytes and keeps archived PDFs private and individually recoverable',async t=>{
  const home=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'nzos-')))
  t.after(()=>fs.rmSync(home,{recursive:true,force:true}))
  const old=path.join(home,'old')
  fs.mkdirSync(old)
  const sql=await require('sql.js')()
  const db=new sql.Database()
  db.run("CREATE TABLE app_metadata(key,value);INSERT INTO app_metadata VALUES('schema_version','1');CREATE TABLE snapshot_rows(id);CREATE TABLE snapshot_manifest(id);CREATE TABLE offline_mutation_outbox(state);INSERT INTO offline_mutation_outbox VALUES('pending')")
  const bytes=Buffer.from(db.export())
  db.close()
  const file='nizamia-app2a.sqlite'
  fs.writeFileSync(path.join(old,file),bytes)
  const {workspaceRoot,databaseDirectory}=await prepareWorkspace(home,old,home)
  assert.deepEqual(fs.readFileSync(path.join(databaseDirectory,file)),bytes)
  assert.deepEqual(fs.readFileSync(path.join(old,file)),bytes)
  const backups=path.join(workspaceRoot,'Backups')
  assert.deepEqual(fs.readFileSync(path.join(backups,fs.readdirSync(backups)[0])),bytes)
  await assert.rejects(prepareWorkspace(workspaceRoot,old,home),/already contains/)
  const pdf=Buffer.from('%PDF-1.7 fixture')
  const first=archivePdf(workspaceRoot,'../Cutting Plan.pdf',pdf)
  const second=archivePdf(workspaceRoot,'../Cutting Plan.pdf',pdf)
  assert.notEqual(first,second)
  assert.deepEqual(fs.readFileSync(first),pdf)
  assert.equal(fs.statSync(first).mode&0o777,0o600)
  assert.equal(path.dirname(first),path.join(workspaceRoot,'Downloads','Plans'))
  fs.symlinkSync(home,path.join(workspaceRoot,'Downloads','Reports'))
  assert.throws(()=>archivePdf(workspaceRoot,'Report',pdf),/without aliases/)
})
