'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const init=require('sql.js')
const {applyCloudSnapshot}=require('./applyCloudSnapshot.cjs')
async function run(){
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-cloud-safety-'))
 const file=path.join(directory,'nizamia-app2a.sqlite')
 try{
  const SQL=await init({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE standalone_records(id TEXT PRIMARY KEY)')
  db.run("INSERT INTO standalone_records VALUES ('local-work')")
  fs.writeFileSync(file,Buffer.from(db.export()))
  db.close()
  const before=fs.readFileSync(file)
  await assert.rejects(applyCloudSnapshot({directory,tables:{orders:[{id:'cloud-order'}]}}),/Cloud refresh blocked/)
  assert.deepEqual(fs.readFileSync(file),before,'Blocked refresh must preserve database bytes')
  assert.deepEqual(fs.readdirSync(directory),['nizamia-app2a.sqlite'],'Blocked refresh must not create replacement files')
  const clean=new SQL.Database(before)
  clean.run('DELETE FROM standalone_records')
  fs.writeFileSync(file,Buffer.from(clean.export()))
  clean.close()
  const outcome=await applyCloudSnapshot({directory,tables:{orders:[{id:'cloud-order'}],buyers:[],suppliers:[]}})
  assert.equal(outcome.updatedTables,3)
  assert.ok(fs.existsSync(outcome.backup),'Successful refresh must create rollback backup')
  const refreshed=new SQL.Database(fs.readFileSync(file))
  assert.equal(refreshed.exec("SELECT COUNT(*) FROM snapshot_rows WHERE table_name='orders'")[0].values[0][0],1)
  assert.equal(refreshed.exec('PRAGMA integrity_check')[0].values[0][0],'ok')
  refreshed.close()
  console.log('Cloud refresh: unsynced work blocked; safe refresh and backup verified')
 }finally{fs.rmSync(directory,{recursive:true,force:true})}
}
run().catch(e=>{console.error(e);process.exitCode=1})
