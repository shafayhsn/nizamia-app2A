'use strict'
const assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const init=require('sql.js')
const {applyCloudSnapshot,hasAdminCloudSnapshot}=require('./applyCloudSnapshot.cjs')
async function run(){
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-cloud-safety-'))
 const file=path.join(directory,'nizamia-app2a.sqlite')
 try{
  const SQL=await init({locateFile:()=>require.resolve('sql.js/dist/sql-wasm.wasm')})
  const db=new SQL.Database()
  db.run('CREATE TABLE standalone_records(id TEXT PRIMARY KEY)')
  db.run("INSERT INTO standalone_records VALUES ('local-work')")
  fs.writeFileSync(file,Buffer.from(db.export()));db.close()
  assert.equal(await hasAdminCloudSnapshot(directory),false)
 const outcome=await applyCloudSnapshot({directory,adminScope:true,tables:{orders:[{id:'cloud-order'}],buyers:[],suppliers:[]}})
  assert.equal(outcome.updatedTables,3)
  assert.equal(await hasAdminCloudSnapshot(directory),true)
  assert.ok(fs.existsSync(outcome.backup),'Refresh must create rollback backup')
  let refreshed=new SQL.Database(fs.readFileSync(file))
  assert.equal(refreshed.exec('SELECT COUNT(*) FROM standalone_records')[0].values[0][0],1,'Local standalone work must survive')
  assert.equal(refreshed.exec("SELECT COUNT(*) FROM snapshot_rows WHERE table_name='orders'")[0].values[0][0],1)
  refreshed.run("CREATE TABLE offline_draft_journal(state TEXT)")
  refreshed.run("INSERT INTO offline_draft_journal VALUES ('pending')")
  fs.writeFileSync(file,Buffer.from(refreshed.export()));refreshed.close()
  const before=fs.readFileSync(file),files=fs.readdirSync(directory)
  await assert.rejects(applyCloudSnapshot({directory,tables:{orders:[{id:'new-cloud-order'}]}}),/pending\/conflicted drafts/)
  assert.deepEqual(fs.readFileSync(file),before,'Blocked refresh must preserve bytes')
  assert.deepEqual(fs.readdirSync(directory),files,'Blocked refresh must not create a backup')
  console.log('Cloud refresh: standalone work preserved, pending drafts blocked, backup verified')
 }finally{fs.rmSync(directory,{recursive:true,force:true})}
}
run().catch(e=>{console.error(e);process.exitCode=1})
