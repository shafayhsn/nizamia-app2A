'use strict'
const assert=require('node:assert/strict')
const {PAGES,REQUIREMENTS,auditCoverage}=require('./offlinePageCoverage.cjs')
const {REQUIRED,assessOfflineReadiness}=require('./offlineReadiness.cjs')
const {validateInventory,planSchema}=require('./offlineSchemaAlignment.cjs')
const nav=PAGES.map(key=>({key}))
const overviews=Object.fromEntries(PAGES.map(key=>[key,{status:'needs-live-verification'}]))
assert.equal(new Set(PAGES).size,PAGES.length,'Duplicate page key')
assert.ok(PAGES.every(key=>Array.isArray(REQUIREMENTS[key])&&REQUIREMENTS[key].length),'Every page must have requirements')
assert.equal(auditCoverage(nav,overviews).complete,true)
assert.deepEqual(auditCoverage(nav.slice(1),overviews).missing,[PAGES[0]])
assert.deepEqual(auditCoverage(nav,[...Object.entries(overviews)].slice(1).reduce((a,[k,v])=>(a[k]=v,a),{})).missingOverviews,[PAGES[0]])
assert.deepEqual(auditCoverage([...nav,{key:'unexpected'}],overviews).unknown,['unexpected'])
const empty=assessOfflineReadiness()
assert.equal(empty.readyForDrafts,false)
assert.equal(empty.readyForSync,false)
assert.equal(empty.mode,'locked')
assert.deepEqual(empty.missing,REQUIRED)
const draftOnly=assessOfflineReadiness({signedEnrollment:true,pinnedServerKey:true,authenticatedSession:true,scopedEditGrant:true,snapshotIntegrity:true})
assert.equal(draftOnly.readyForDrafts,true)
assert.equal(draftOnly.readyForSync,false,'Local draft readiness must not enable cloud writes')
assert.deepEqual(draftOnly.missing,['serverSyncEndpoint','conditionalCloudWrites'])
assert.equal(assessOfflineReadiness(Object.fromEntries(REQUIRED.map(k=>[k,true]))).readyForSync,true)
const inventory={tableCount:2,columnCount:3,tables:[{table_name:'orders',columns:[{name:'id',type:'uuid'},{name:'notes',type:'text'}]},{table_name:'users',columns:[{name:'id',type:'uuid'}]}]}
assert.equal(validateInventory(inventory),true)
assert.throws(()=>planSchema({inventory,allowedTables:['users']}),/allowlist/)
const plan=planSchema({inventory,allowedTables:['orders']})
assert.equal(plan.canApply,true)
assert.equal(plan.counts.created,1)
assert.equal(plan.operations[0].kind,'create')
const conflict=planSchema({inventory,allowedTables:['orders'],localTables:{offline_orders:[{name:'id',type:'INTEGER'},{name:'notes',type:'TEXT'}]}})
assert.equal(conflict.canApply,false)
assert.equal(conflict.counts.manualReview,1)
assert.equal(conflict.operations[0].kind,'manual-review')
console.log('Desktop page coverage, offline readiness and conservative schema tests passed (no database or network writes)')
