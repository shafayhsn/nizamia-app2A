'use strict'
const {test}=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const os=require('node:os')
const path=require('node:path')
const initSqlJs=require('sql.js')
const {backupDatabaseBeforeUpdate}=require('./desktopUpdateBackup.cjs')

test('pre-update backup keeps pending SQLite edits byte for byte',async t=>{
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'app2a-update-backup-'))
 t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
 const directory=path.join(root,'live'),backupRoot=path.join(root,'backups')
 fs.mkdirSync(directory)
 const source=path.join(directory,'nizamia-app2a.sqlite')
 const SQL=await initSqlJs()
 const db=new SQL.Database()
 db.run('CREATE TABLE offline_draft_journal(note TEXT)')
 db.run("INSERT INTO offline_draft_journal VALUES ('pending edit')")
 const bytes=Buffer.from(db.export())
 db.close()
 fs.writeFileSync(source,bytes)
 const result=await backupDatabaseBeforeUpdate({directory,backupRoot})
 assert.deepEqual(fs.readFileSync(result.file),bytes)
 assert.deepEqual(fs.readFileSync(source),bytes)
 await assert.rejects(backupDatabaseBeforeUpdate({directory,backupRoot:directory}),/outside/)
 fs.writeFileSync(source,Buffer.alloc(2048,91))
 await assert.rejects(backupDatabaseBeforeUpdate({directory,backupRoot}),/invalid SQLite header/)
 fs.unlinkSync(source)
 await assert.rejects(backupDatabaseBeforeUpdate({directory,backupRoot}),/ENOENT/)
 assert.deepEqual(fs.readdirSync(backupRoot),[path.basename(result.file)])
})
